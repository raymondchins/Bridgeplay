#include <dirent.h>
#include <limits.h>
#include <errno.h>
#include <fcntl.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#define ICON_LIMIT (16 * 1024 * 1024)
#define PLIST_LIMIT (64 * 1024)

typedef struct {
    unsigned char *bytes;
    size_t         length;
} blob_t;

static int directory_at(int parent, const char *path) {
    return openat(parent, path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW_ANY | O_CLOEXEC);
}

static int same_time(struct timespec a, struct timespec b) {
    return a.tv_sec == b.tv_sec && a.tv_nsec == b.tv_nsec;
}

static int read_at(int parent, const char *name, size_t limit, blob_t *out) {
    *out = (blob_t){0};
    int fd = openat(parent, name, O_RDONLY | O_NONBLOCK | O_NOFOLLOW | O_CLOEXEC);
    if (fd < 0) return 0;
    struct stat before, after;
    int ok = fstat(fd, &before) == 0 && S_ISREG(before.st_mode) && before.st_size > 0 &&
             (uint64_t)before.st_size <= limit && (out->bytes = malloc((size_t)before.st_size));
    size_t done = 0;
    while (ok && done < (size_t)before.st_size) {
        ssize_t n = read(fd, out->bytes + done, (size_t)before.st_size - done);
        if (n < 0 && errno == EINTR) continue;
        if (n <= 0) ok = 0;
        else done += (size_t)n;
    }
    ok = ok && fstat(fd, &after) == 0 && before.st_size == after.st_size &&
         same_time(before.st_mtimespec, after.st_mtimespec) &&
         same_time(before.st_ctimespec, after.st_ctimespec);
    close(fd);
    if (ok) {
        out->length = done;
    } else {
        free(out->bytes);
        out->bytes = NULL;
    }
    return ok;
}

static int same_blob(const blob_t *a, const blob_t *b) {
    return a->length == b->length && memcmp(a->bytes, b->bytes, a->length) == 0;
}

// Accepts only the run.sh Steam writes for this app, unedited.
static int is_shortcut(int app, const char *app_id) {
    char want[128];
    int n = snprintf(want, sizeof(want),
                     "#!/bin/bash\n# autogenerated file - do not edit\n\nopen steam://run/%s\n\n", app_id);
    int macos = directory_at(app, "Contents/MacOS");
    if (macos < 0) return 0;
    blob_t data;
    int ok = n < (int)sizeof(want) && read_at(macos, "run.sh", sizeof(want), &data);
    close(macos);
    if (!ok) return 0;
    ok = data.length == (size_t)n && memcmp(data.bytes, want, data.length) == 0;
    free(data.bytes);
    return ok;
}

static int same_entry(int parent, const char *name, int fd) {
    struct stat path, opened;
    return fstatat(parent, name, &path, AT_SYMLINK_NOFOLLOW) == 0 && fstat(fd, &opened) == 0 &&
           path.st_dev == opened.st_dev && path.st_ino == opened.st_ino;
}

static void replace_icon(int parent, const char *name, int app, int resources, const blob_t *icon) {
    char temp[64];
    snprintf(temp, sizeof(temp), ".bridgeplay-icon-%d-%08x", (int)getpid(), arc4random());
    int fd = openat(resources, temp, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0644);
    if (fd < 0) return;
    size_t done = 0;
    while (done < icon->length) {
        ssize_t n = write(fd, icon->bytes + done, icon->length - done);
        if (n < 0 && errno == EINTR) continue;
        if (n <= 0) break;
        done += (size_t)n;
    }
    int error = close(fd);
    // Finder keeps showing a bundle's cached icon until the bundle's mtime changes.
    if (done == icon->length && error == 0 && same_entry(parent, name, app) &&
        renameat(resources, temp, resources, "shortcut.icns") == 0)
        futimens(app, NULL);
    unlinkat(resources, temp, 0);
}

static void update_folder(int home, const char *folder, const char *app_id,
                          const blob_t *icon, const blob_t *stock) {
    int parent = directory_at(home, folder);
    if (parent < 0) return;
    DIR *dir = fdopendir(parent);
    if (!dir) {
        close(parent);
        return;
    }
    struct dirent *entry;
    while ((entry = readdir(dir))) {
        size_t len = strlen(entry->d_name);
        if (len <= 4 || strcmp(entry->d_name + len - 4, ".app") != 0) continue;
        int app = directory_at(parent, entry->d_name);
        if (app < 0) continue;
        int resources = is_shortcut(app, app_id) ? directory_at(app, "Contents/Resources") : -1;
        blob_t current;
        if (resources >= 0 && read_at(resources, "shortcut.icns", ICON_LIMIT, &current)) {
            if (same_blob(&current, stock)) replace_icon(parent, entry->d_name, app, resources, icon);
            free(current.bytes);
        }
        if (resources >= 0) close(resources);
        close(app);
    }
    closedir(dir);
}

void np_shortcuts_icons(const char *home, const char *app_id, const char *icon_path, const char *stock_path) {
    if (!home || home[0] != '/' || !app_id || !icon_path || !stock_path) return;
    blob_t icon, stock;
    read_at(AT_FDCWD, icon_path, ICON_LIMIT, &icon);
    read_at(AT_FDCWD, stock_path, ICON_LIMIT, &stock);
    int dir = open(home, O_RDONLY | O_DIRECTORY | O_CLOEXEC);
    if (dir >= 0 && icon.bytes && stock.bytes && !same_blob(&icon, &stock)) {
        update_folder(dir, "Applications", app_id, &icon, &stock);
        update_folder(dir, "Desktop", app_id, &icon, &stock);
    }
    if (dir >= 0) close(dir);
    free(icon.bytes);
    free(stock.bytes);
}

static size_t count_of(const blob_t *b, const char *needle, size_t *last) {
    size_t count = 0, n = strlen(needle);
    for (const unsigned char *p = b->bytes, *end = b->bytes + b->length;
         (p = memmem(p, (size_t)(end - p), needle, n)); p += n) {
        *last = (size_t)(p - b->bytes);
        count++;
    }
    return count;
}

// Steam's Info.plist with the games category added before its only </dict>, indented like the
// line above, every other byte kept. NULL when it isn't the flat dict Steam writes, or already
// has a category.
static unsigned char *with_games_category(const blob_t *plist, size_t *length) {
    size_t open_at = 0, close_at = 0, unused;
    if (count_of(plist, "<dict>", &open_at) != 1 || count_of(plist, "</dict>", &close_at) != 1 ||
        open_at > close_at || count_of(plist, "LSApplicationCategoryType", &unused) != 0 ||
        count_of(plist, "<string>run.sh</string>", &unused) != 1)
        return NULL;
    size_t line = close_at;
    while (line > 0 && (plist->bytes[line - 1] == '\t' || plist->bytes[line - 1] == ' ')) line--;
    size_t indent = close_at - line;
    if ((line > 0 && plist->bytes[line - 1] != '\n') || indent > 16) return NULL;
    char added[160];
    int n = snprintf(added, sizeof(added),
                     "%.*s\t<key>LSApplicationCategoryType</key>\n%.*s\t<string>public.app-category.games</string>\n",
                     (int)indent, (const char *)plist->bytes + line, (int)indent, (const char *)plist->bytes + line);
    if (n <= 0 || n >= (int)sizeof(added)) return NULL;
    unsigned char *out = malloc(plist->length + (size_t)n);
    if (!out) return NULL;
    memcpy(out, plist->bytes, line);
    memcpy(out + line, added, (size_t)n);
    memcpy(out + line + n, plist->bytes + line, plist->length - line);
    *length = plist->length + (size_t)n;
    return out;
}

static int add_games_category(int parent, const char *name, int app) {
    int contents = directory_at(app, "Contents");
    if (contents < 0) return 0;
    struct stat st;
    blob_t plist, again;
    size_t length = 0;
    unsigned char *edited = NULL;
    int done = 0;
    if (fstatat(contents, "Info.plist", &st, AT_SYMLINK_NOFOLLOW) == 0 &&
        read_at(contents, "Info.plist", PLIST_LIMIT, &plist)) {
        edited = with_games_category(&plist, &length);
        char temp[64];
        snprintf(temp, sizeof(temp), ".bridgeplay-plist-%d-%08x", (int)getpid(), arc4random());
        int fd = edited ? openat(contents, temp, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0600) : -1;
        if (fd >= 0) {
            size_t written = 0;
            while (written < length) {
                ssize_t n = write(fd, edited + written, length - written);
                if (n < 0 && errno == EINTR) continue;
                if (n <= 0) break;
                written += (size_t)n;
            }
            int ok = written == length && fchmod(fd, st.st_mode & 0777) == 0;
            ok = close(fd) == 0 && ok;
            // Steam rewrites the shortcut when it is made again: only a file still unchanged is replaced.
            ok = ok && read_at(contents, "Info.plist", PLIST_LIMIT, &again);
            if (ok) {
                ok = same_blob(&plist, &again);
                free(again.bytes);
            }
            if (ok && same_entry(parent, name, app) && renameat(contents, temp, contents, "Info.plist") == 0) {
                futimens(app, NULL);
                done = 1;
            }
            unlinkat(contents, temp, 0);
        }
        free(plist.bytes);
    }
    free(edited);
    close(contents);
    return done;
}

void np_shortcuts_games(const char *home, const char *app_id, void (*changed)(const char *path)) {
    if (!home || home[0] != '/' || !app_id) return;
    int dir = open(home, O_RDONLY | O_DIRECTORY | O_CLOEXEC);
    int parent = dir >= 0 ? directory_at(dir, "Applications") : -1;
    if (dir >= 0) close(dir);
    DIR *apps = parent >= 0 ? fdopendir(parent) : NULL;
    if (!apps) {
        if (parent >= 0) close(parent);
        return;
    }
    struct dirent *entry;
    while ((entry = readdir(apps))) {
        size_t len = strlen(entry->d_name);
        if (len <= 4 || strcmp(entry->d_name + len - 4, ".app") != 0) continue;
        int app = directory_at(parent, entry->d_name);
        if (app < 0) continue;
        if (is_shortcut(app, app_id) && add_games_category(parent, entry->d_name, app) && changed) {
            char path[PATH_MAX];
            int n = snprintf(path, sizeof(path), "%s/Applications/%s", home, entry->d_name);
            if (n > 0 && n < (int)sizeof(path)) changed(path);
        }
        close(app);
    }
    closedir(apps);
}
